@pytest.mark.parametrize("i", range(len(enqueue_test_cases)))
def test_EnQueue(i):
    initial, item, priority, expected = enqueue_test_cases[i]
    queue = list(initial)
    EnQueue(queue, item, priority)
    assert queue == expected

